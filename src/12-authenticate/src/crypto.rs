//! HMAC-SHA256 challenge-response math (hardware-free, reusable on host).

use crate::constants::{KEY_LEN, MAC_LEN, NONCE_LEN};
use hmac::{Hmac, Mac as MacTrait};
use sha2::Sha256;

/// Host/device key type (32 bytes).
pub type Key = [u8; KEY_LEN];
/// Challenge nonce (32 bytes).
pub type Nonce = [u8; NONCE_LEN];
/// Response MAC (32 bytes = SHA-256 output).
pub type Mac = [u8; MAC_LEN];

/// Compute `HMAC-SHA256(key, nonce)`.
pub fn sign(key: &Key, nonce: &Nonce) -> Mac {
    let mut mac =
        <Hmac<Sha256> as MacTrait>::new_from_slice(key).expect("HMAC accepts any key size");
    mac.update(nonce);
    let output = mac.finalize().into_bytes();
    let mut res = [0u8; MAC_LEN];
    res.copy_from_slice(&output);
    res
}

/// Constant-time verification: true iff `expected` equals `sign(key, nonce)`.
pub fn verify(expected: &Mac, key: &Key, nonce: &Nonce) -> bool {
    let mut mac =
        <Hmac<Sha256> as MacTrait>::new_from_slice(key).expect("HMAC accepts any key size");
    mac.update(nonce);
    mac.verify_slice(expected).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    // Vector computed from the exact our-API inputs (key/mac in hex):
    // key  = 00..1f (32 bytes), nonce = 00..1f (32 bytes)
    const K1: Key = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ];
    const N1: Nonce = [
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e,
        0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d,
        0x1e, 0x1f,
    ];
    #[rustfmt::skip]
    const M1: Mac = [
        0xe8, 0x49, 0x9b, 0xe4, 0xf1, 0x98, 0x0d, 0x68, 0xf1, 0x32, 0x22, 0xa4, 0x18, 0xdf, 0x5c,
        0xbd, 0x97, 0xd5, 0x3f, 0xdd, 0xf5, 0x90, 0xc2, 0x10, 0x8e, 0x22, 0xd4, 0x00, 0x05, 0xb7,
        0x07, 0x13,
    ];

    // RFC 4231 Test Case 1 style: 32-byte 0x0b key, nonce = 0x20..0x3f.
    const K2: Key = [0x0b; 32];
    const N2: Nonce = [
        0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2a, 0x2b, 0x2c, 0x2d, 0x2e,
        0x2f, 0x30, 0x31, 0x32, 0x33, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3a, 0x3b, 0x3c, 0x3d,
        0x3e, 0x3f,
    ];
    #[rustfmt::skip]
    const M2: Mac = [
        0x08, 0x96, 0x74, 0x48, 0xb8, 0xc7, 0x40, 0xaf, 0x61, 0xbd, 0xf3, 0xe8, 0xa3, 0x0f, 0x47,
        0xc9, 0xa7, 0xdf, 0x27, 0xa0, 0x6d, 0x2f, 0x52, 0x0f, 0xe0, 0xbc, 0xab, 0xb9, 0xe3, 0xb2,
        0xb2, 0x1e,
    ];

    #[test]
    fn vector_1() {
        assert_eq!(sign(&K1, &N1), M1);
    }

    #[test]
    fn vector_2_constant_time_verify() {
        let mac = sign(&K2, &N2);
        assert_eq!(mac, M2);
        assert!(verify(&mac, &K2, &N2));
        assert!(!verify(&M1, &K2, &N2));
        // mutated ciphertext must fail
        let mut bad = mac;
        bad[0] ^= 0xff;
        assert!(!verify(&bad, &K2, &N2));
    }

    #[test]
    fn different_nonce_different_mac() {
        let mut n = N1;
        n[31] ^= 1;
        assert_ne!(sign(&K1, &N1), sign(&K1, &n));
    }
}